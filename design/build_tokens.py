"""
Build tokens.css from the design system's tokens.json (light theme).

Run after the kit changes:  python design/build_tokens.py
The app reads design/tokens.css and design/bundle.css; it never hard-codes a colour.
The script also draws static/mark.png, the browser-tab icon: the kit's plain action square.
"""
import json
import re
from pathlib import Path

HERE = Path(__file__).resolve().parent
THEME = "light"


def css_value(value) -> str:
    """'{sand-0}' becomes var(--sand-0); anything else is used as it is."""
    value = value.get(THEME) if isinstance(value, dict) else value
    return re.sub(r"\{([^}]+)\}", r"var(--\1)", str(value))


def render(kit: dict) -> str:
    """The text of tokens.css for a tokens.json. A test compares it with the file on disk."""
    lines = [f"/* Generated by build_tokens.py from tokens.json ({kit['name']}, {THEME} theme). Do not edit. */"]
    for font in kit["type"]["fonts"]:
        name = Path(font["file"]).name
        if not (HERE.parent / "static" / name).exists():
            continue    # the app ships the product faces only
        lines.append(f'@font-face {{ font-family: "{font["family"]}"; src: url("app/static/{name}") format("woff2"); '
                     f'font-weight: {font["weight"]}; font-style: {font["style"]}; font-display: swap; }}')
    lines.append(":root {")
    for token in kit["color"]["tokens"]:
        lines.append(f"  --{token['name']}: {css_value(token['value'])};")
    for family, stack in kit["type"]["families"].items():
        lines.append(f"  --font-{family}: {stack};")
    for group in ("spacing", "radius", "size", "shadow"):
        for token in kit[group]["tokens"]:
            lines.append(f"  --{token['name']}: {css_value(token['value'])};")
    lines.append("}")
    return "\n".join(lines) + "\n"


def main() -> None:
    kit = json.loads((HERE / "tokens.json").read_text(encoding="utf-8"))
    text = render(kit)
    (HERE / "tokens.css").write_text(text, encoding="utf-8")
    print(f"wrote tokens.css with {text.count(';')} declarations")
    write_mark(kit)


def write_mark(kit: dict) -> None:
    """The browser-tab icon: a plain square in action-primary. The kit has no logo, and this is not one."""
    from PIL import Image, ImageDraw     # Pillow comes with Streamlit

    raw = {t["name"]: (t["value"][THEME] if isinstance(t["value"], dict) else t["value"]) for t in kit["color"]["tokens"]}
    value = raw["action-primary"]
    while value.startswith("{"):
        value = raw[value.strip("{}")]
    image = Image.new("RGBA", (128, 128), (0, 0, 0, 0))
    ImageDraw.Draw(image).rounded_rectangle((8, 8, 120, 120), radius=24, fill=value)
    image.save(HERE.parent / "static" / "mark.png")
    print("wrote static/mark.png")


if __name__ == "__main__":
    main()
